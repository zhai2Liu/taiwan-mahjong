import fs from 'node:fs';
import { createHash } from 'node:crypto';
const sources=['TRAINING-DRAFTS.json','TRAINING-REVIEW-CANDIDATES.json'];
const questions=sources.flatMap(file=>JSON.parse(fs.readFileSync(new URL('../'+file,import.meta.url),'utf8')).cases)
  .filter(c=>c.purpose==='training');
if(questions.length!==9||new Set(questions.map(c=>c.id)).size!==9||questions.some(c=>c.reviewStatus!=='model-reviewed-not-calibrated')) throw Error('Training content requires review');
const data=questions.map(({id,prompt,choices,accepted,derivation,board=[]})=>({id,prompt,choices,accepted,derivation,board}));
// ponytail: bundled reviewed content only; external question import requires its own validation contract.
const revision=createHash('sha256').update(JSON.stringify(data)).digest('hex');
fs.writeFileSync(new URL('../src/training-data.ts',import.meta.url),'// Generated by scripts/prepare-training.mjs; edit the source question JSON.\nexport const trainingContentRevision = '+JSON.stringify(revision)+';\nexport const trainingQuestions = '+JSON.stringify(data,null,2)+';\n');
